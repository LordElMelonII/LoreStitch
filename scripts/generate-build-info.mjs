// Generates `src/app/core/models/build-info.prod.ts`, which the production
// build swaps in for `build-info.ts` via `fileReplacements` (angular.json), so
// the About dialog can report the exact version, build time and commit that
// shipped. Runs automatically before every `npm run build`. The BuildInfo
// interface lives in build-info.types.ts (shared with the dev placeholder) so
// this template can never drift from the type consumers import.
import { execSync } from 'node:child_process';
import fs from 'node:fs';

const pkg = JSON.parse(fs.readFileSync(new URL('../package.json', import.meta.url), 'utf8'));
if (!pkg.version) {
  throw new Error('package.json has no "version" field — cannot generate build info');
}

let sha = null;
try {
  sha =
    execSync('git rev-parse HEAD', {
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'ignore'],
    }).trim() || null;
} catch {
  // Not a git checkout (release archive, Docker copy) — fall back to null.
}

const timestamp = new Date().toISOString();

const content = `// Generated by scripts/generate-build-info.mjs — do not edit.
// Swapped in for build-info.ts by the production build's fileReplacements.
import { InjectionToken } from '@angular/core';
import { type BuildInfo } from './build-info.types';

export const APP_BUILD_INFO = new InjectionToken<BuildInfo>('APP_BUILD_INFO', {
  factory: (): BuildInfo => ({
    version: ${JSON.stringify(pkg.version)},
    buildTimestamp: ${JSON.stringify(timestamp)},
    gitCommitSha: ${JSON.stringify(sha)},
  }),
});
`;

fs.writeFileSync(new URL('../src/app/core/models/build-info.prod.ts', import.meta.url), content);
console.log(`build info: v${pkg.version}, ${timestamp}, commit ${sha ?? 'unavailable'}`);
